import { PGlite } from '@electric-sql/pglite';
import path from 'path';
import { fileURLToPath } from 'url';
import fs from 'fs';
const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const dataDir = path.join(__dirname, 'data');
fs.rmSync(dataDir, { recursive: true, force: true });
fs.mkdirSync(dataDir, { recursive: true });
const dbPath = path.join(dataDir, 'kanban.db');
const db = await PGlite.create(dbPath);
await db.exec(`CREATE TABLE cards (id SERIAL PRIMARY KEY, column_id INTEGER, position NUMERIC)`);
const res = await db.query('SELECT COALESCE(MAX(position), -1) as maxPos FROM cards WHERE column_id = $1', [1]);
console.log(res.rows);
await db.close();
