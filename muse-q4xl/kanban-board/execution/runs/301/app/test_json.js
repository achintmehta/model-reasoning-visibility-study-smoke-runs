import { PGlite } from '@electric-sql/pglite';
import path from 'path';
import { fileURLToPath } from 'url';
const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const dataDir = path.join(__dirname, 'data');
import fs from 'fs';
fs.rmSync(dataDir, { recursive: true, force: true });
fs.mkdirSync(dataDir, { recursive: true });
const dbPath = path.join(dataDir, 'kanban.db');
const db = await PGlite.create(dbPath);
await db.exec(`CREATE TABLE test (id SERIAL PRIMARY KEY, pos NUMERIC NOT NULL)`);
await db.query('INSERT INTO test (pos) VALUES ($1) RETURNING id, pos', [0]);
const res = await db.query('SELECT id, pos FROM test');
console.log('rows', res.rows);
console.log('json', JSON.stringify(res.rows));
await db.close();
